package cmd

import (
	"strings"
	"testing"

	"github.com/spf13/cobra"
	"github.com/stretchr/testify/require"
)

// Văn bản trợ giúp người dùng đọc phải gọi sản phẩm là dew, không phải
// tên upstream (module, crush.json, biến CRUSH_* giữ nguyên, nhưng chúng không
// xuất hiện trong phần mô tả của các lệnh này).
func TestHelpTextNamesDew(t *testing.T) {
	// Không t.Parallel(): cobra gộp cờ persistent của cha vào Flags() khi một test khác
	// thực thi lệnh, và đọc FlagSet lúc đang bị ghi là data race.
	for _, c := range []*cobra.Command{dirsCmd, logsCmd, loginCmd, logoutCmd, schemaCmd, statsCmd} {
		// LocalFlags: chỉ cờ khai riêng cho lệnh này, không lẫn cờ kế thừa từ lệnh gốc
		// (giá trị mặc định của --host có chữ crush trong đường dẫn socket).
		text := strings.Join([]string{c.Short, c.Long, c.Example, c.LocalFlags().FlagUsages()}, "\n")
		require.NotContains(t, strings.ToLower(text), "crush", "help of `%s` mentions the upstream name", c.Name())
	}

	// Mô tả dài của các lệnh này nêu tên sản phẩm bằng đúng chữ dew.
	require.Contains(t, dirsCmd.Long, "Show where dew stores")
	require.Contains(t, logsCmd.Long, "logs generated by dew")
	require.Contains(t, loginCmd.Long, "Login dew to")
	require.Contains(t, logoutCmd.Long, "Logout dew from")
	require.Contains(t, schemaCmd.Long, "dew configuration file")
	require.Contains(t, statsCmd.Flags().Lookup("crawl-dir").Usage, "dew projects")
}

// Help của lệnh gốc và `run` là thứ đầu tiên người dùng đọc: phải nói DEW là gì,
// không còn câu giới thiệu và ví dụ của upstream.
func TestRootAndRunHelpDescribeDEW(t *testing.T) {
	require.Contains(t, rootCmd.Short, "Daily Engineering Workspace")
	require.Contains(t, rootCmd.Long, "Daily Engineering Workspace")
	for _, c := range []*cobra.Command{rootCmd, runCmd} {
		text := strings.ToLower(strings.Join([]string{c.Short, c.Long, c.Example}, "\n"))
		for _, s := range []string{"glamorous", "pokémon", "charm.land", "hot readme"} {
			require.NotContains(t, text, s, "help of `%s` still has upstream text", c.Name())
		}
	}
}

// Help của `dew routine` không hứa "checkout không bị đụng" (lớp chặn là guard-rail, không phải
// sandbox), gc không còn nói lượt mới nhất luôn được giữ (Q4), và có lệnh rm.
func TestRoutineHelpSaysGuardRailNotSandbox(t *testing.T) {
	require.NotContains(t, routineCmd.Long, "never touched")
	require.Contains(t, routineCmd.Long, "guard-rail, not a sandbox")
	require.Contains(t, routineCmd.Long, "shared .git")
	sub := map[string]*cobra.Command{}
	for _, c := range routineCmd.Commands() {
		sub[c.Name()] = c
	}
	require.Contains(t, sub, "rm")
	require.NotContains(t, sub["gc"].Short+sub["gc"].Long+routineCmd.Long, "newest")
}
