PRIORITY = ["CAP", "ROUTE", "PI", "OVH", "RACE", "ZOMB", "FALSE", "DEL", "HOST", "SEC"]

def main(path):
    kinds = {}
    for line in open(path, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if p[0] == "num":
            continue
        kinds[int(p[0])] = p[1]
    missing = sorted(set(kinds) - set(F))
    extra = sorted(set(F) - set(kinds))
    assert not missing and not extra, (missing, extra)
    prim = collections.Counter()
    anyf = collections.defaultdict(lambda: collections.Counter())
    members = collections.defaultdict(list)
    for n, v in F.items():
        fams = v.split(",")
        prim[(fams[0], kinds[n])] += 1
        for f in fams:
            anyf[f][kinds[n]] += 1
            members[f].append((n, kinds[n], f == fams[0]))
    print("family\tprimary_issue\tprimary_pr\tany_issue\tany_pr")
    allf = sorted(anyf, key=lambda f: -(anyf[f]["issue"]))
    for f in allf:
        print(f"{f}\t{prim[(f,'issue')]}\t{prim[(f,'PR')]}\t{anyf[f]['issue']}\t{anyf[f]['PR']}")
    if len(sys.argv) > 2:
        for f in PRIORITY:
            iss = sorted((n for n, k, _ in members[f] if k == "issue"), reverse=True)
            prs = sorted((n for n, k, _ in members[f] if k == "PR"), reverse=True)
            print(f"\n{f} issues({len(iss)}): " + " ".join("#%d" % n for n in iss))
            print(f"{f} PRs({len(prs)}): " + " ".join("#%d" % n for n in prs))

main(sys.argv[1])
